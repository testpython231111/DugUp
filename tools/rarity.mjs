// Dug Up — precomputes answer rarity from Wikipedia page views (Feature Spec 05).
// Fetches the last 60 days of page views for every answer, ranks the answers of each prompt and writes
// js/data/rarity.js. Run it about once a month, check the diff, run `npm test`, commit.
//
//   node tools/rarity.mjs              fetch and write js/data/rarity.js
//   node tools/rarity.mjs --dry-run    fetch and report, write nothing
//
// Built-in modules only (Node 20+). Nothing is written if more than 5 % of the requests fail.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadGame } from './load-game.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HTML_FILE = path.join(ROOT, 'index.html');
const OUT_FILE = path.join(ROOT, 'js', 'data', 'rarity.js');
const DAYS = 60;
const BATCH = 50;                 // the API's limit on titles per request
const PAUSE_MS = 200;             // between requests, to be gentle with Wikipedia
const MAX_FAIL_SHARE = 0.05;
const USER_AGENT = 'DugUpRarity/1.0 (https://dugup.eu)';

// Rank one prompt's answers by page views: the same rule the browser used before Spec 05 (Live.prepare).
// Returns {display: [tier, views]}, or null when too few answers have views (then the offline tiers are used).
export function rankPrompt(answers, views){
  const ranked = answers.filter(a => views[a.wiki] > 0).map(a => ({ a, v: views[a.wiki] })).sort((x, y) => y.v - x.v);
  if (ranked.length < Math.max(3, Math.floor(answers.length * 0.6))) return null;
  const N = ranked.length, out = {};
  ranked.forEach((e, i) => {
    const q = (i + 0.5) / N;
    out[e.a.display] = [q < 0.12 ? 1 : q < 0.27 ? 2 : q < 0.47 ? 3 : q < 0.67 ? 4 : q < 0.85 ? 5 : 6, e.v];
  });
  return out;
}

export const sleep = ms => new Promise(r => setTimeout(r, ms));

// GET with the Dug Up User-Agent, a 20 s timeout and two retries. Also used by tools/summaries.mjs.
export async function getJSON(url){
  let last;
  for (let attempt = 0; attempt < 3; attempt++){
    if (attempt) await sleep(1000 * attempt * attempt);
    try{
      const r = await fetch(url, { headers: { 'User-Agent': USER_AGENT, 'Api-User-Agent': USER_AGENT }, signal: AbortSignal.timeout(20000) });
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      const j = await r.json();
      if (j.error) throw new Error(`API error ${j.error.code}`);
      return j;
    }catch(e){ last = e; }
  }
  throw last;
}

// Page views summed over DAYS for up to BATCH titles, following redirects, normalisation and continuation.
async function fetchBatch(api, titles){
  const normMap = {}, redirMap = {}, sums = {}, out = {};
  let cont = null, guard = 0, requests = 0;
  do {
    const params = new URLSearchParams({ action: 'query', format: 'json', formatversion: '2', prop: 'pageviews', pvipdays: String(DAYS), redirects: '1', titles: titles.join('|') });
    if (cont) Object.keys(cont).forEach(k => params.set(k, cont[k]));
    const j = await getJSON(api + '?' + params.toString()); requests++;
    const q = j.query || {};
    (q.normalized || []).forEach(x => { normMap[x.from] = x.to; });
    (q.redirects || []).forEach(x => { redirMap[x.from] = x.to; });
    (q.pages || []).forEach(pg => {
      if (pg.pageviews && sums[pg.title] == null){ let s = 0; for (const k in pg.pageviews) s += pg.pageviews[k] || 0; sums[pg.title] = s; }
    });
    cont = j.continue || null; guard++;
    if (cont) await sleep(PAUSE_MS);
  } while (cont && guard < 20);
  titles.forEach(t => { let x = normMap[t] || t; x = redirMap[x] || x; if (sums[x] != null) out[t] = sums[x]; });
  return { views: out, requests };
}

function rarityLiteral(updated, perPrompt){
  const lines = Object.keys(perPrompt).sort().map(id =>
    `${id}:{` + Object.entries(perPrompt[id]).map(([d, [t, v]]) => `${JSON.stringify(d)}:[${t},${v}]`).join(',') + '},');
  return `/* Answer rarity — GENERATED by tools/rarity.mjs on ${updated}. Do not edit by hand (Feature Spec 05).
   p.<prompt id>.<answer display> = [tier 1–6, Wikipedia page views over the ${DAYS} days before ${updated}].
   Answers that are missing here use the tier written in PROMPT_DATA. */
const RARITY = {updated:'${updated}', days:${DAYS}, p:{
${lines.join('\n')}
}};
`;
}

async function main(){
  const argv = process.argv.slice(2);
  const dry = argv.includes('--dry-run');
  const apiArg = argv.indexOf('--api');                       // only for testing failures
  const api = apiArg !== -1 ? argv[apiArg + 1] : 'https://en.wikipedia.org/w/api.php';

  // Load the game without any rarity file, so a stale one can't affect anything.
  const G = loadGame(HTML_FILE, fs.readFileSync(HTML_FILE, 'utf8'), { 'js/data/rarity.js': '' });
  const prompts = Array.from(G.PROMPTS);
  const titles = [...new Set(prompts.flatMap(p => Array.from(p.answers, a => a.wiki)))];
  const batches = [];
  for (let i = 0; i < titles.length; i += BATCH) batches.push(titles.slice(i, i + BATCH));
  console.log(`${prompts.length} prompts, ${titles.length} Wikipedia titles, ${batches.length} batches.`);

  const views = {};
  let failed = 0, requests = 0;
  for (let i = 0; i < batches.length; i++){
    try{
      const r = await fetchBatch(api, batches[i]);
      Object.assign(views, r.views); requests += r.requests;
    }catch(e){
      failed++;
      console.warn(`batch ${i + 1} failed: ${e.message}`);
      if (failed > batches.length * MAX_FAIL_SHARE){ console.error(`More than ${MAX_FAIL_SHARE * 100} % of the batches failed. Nothing was written.`); process.exit(1); }
    }
    if ((i + 1) % 20 === 0 || i + 1 === batches.length) console.log(`  ${i + 1}/${batches.length} batches`);
    await sleep(PAUSE_MS);
  }

  const perPrompt = {}, offline = [];
  for (const p of prompts){
    const r = rankPrompt(Array.from(p.answers), views);
    if (r) perPrompt[p.id] = r; else offline.push(p.id);
  }
  const updated = new Date().toISOString().slice(0, 10);
  const src = rarityLiteral(updated, perPrompt);
  const ranked = Object.values(perPrompt).reduce((n, r) => n + Object.keys(r).length, 0);
  const answers = prompts.reduce((n, p) => n + p.answers.length, 0);
  console.log(`${requests} requests, ${failed} failed batches. ${titles.length - Object.keys(views).length} titles had no views.`);
  console.log(`Ranked ${ranked} of ${answers} answers in ${Object.keys(perPrompt).length} prompts; ${offline.length} prompts keep offline tiers${offline.length ? ': ' + offline.join(', ') : ''}.`);
  console.log(`rarity.js would be ${(Buffer.byteLength(src) / 1024).toFixed(0)} KB.`);
  if (dry){ console.log('Dry run: nothing written.'); return; }
  const eol = fs.existsSync(OUT_FILE) && fs.readFileSync(OUT_FILE, 'utf8').includes('\r\n') ? '\r\n' : '\n';
  fs.writeFileSync(OUT_FILE, src.replace(/\n/g, eol));
  console.log(`Wrote ${OUT_FILE}. Check the diff and run npm test.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
