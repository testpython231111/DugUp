// Dug Up — precomputes the short Wikipedia summaries shown on the reveal screen for rare finds (Feature Spec 06).
// Fetches the plain-text intro of every answer with tier >= 4 (after js/data/rarity.js), trims it to one or two
// sentences and writes js/data/summaries.js. Run it monthly, AFTER tools/rarity.mjs. Text only, never images.
//
//   node tools/summaries.mjs              fetch and write js/data/summaries.js
//   node tools/summaries.mjs --dry-run    fetch and report, write nothing
//
// Built-in modules only (Node 20+). Nothing is written if more than 5 % of the requests fail.
// Wikipedia text is CC BY-SA 4.0; the reveal screen links to the article as attribution.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadGame } from './load-game.mjs';
import { getJSON, sleep } from './rarity.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HTML_FILE = path.join(ROOT, 'index.html');
const OUT_FILE = path.join(ROOT, 'js', 'data', 'summaries.js');
export const MIN_TIER = 4;
const BATCH = 20;                 // the API's limit for intro extracts
const PAUSE_MS = 200;
const MAX_FAIL_SHARE = 0.05;
export const MAX_LEN = 220;
const SHORT = 90, MIN_LEN = 40;

// Abbreviations that end in a full stop without ending a sentence.
const ABBR = /(?:^|[\s(])(?:[A-Z]|St|Mt|Dr|Mr|Mrs|Ms|Jr|Sr|Gen|Maj|Brig|Adm|Cmdr|Col|Capt|Lt|Sgt|Cpl|Gov|Sen|Pres|Prof|Hon|Rev|Fr|Sept|c|ca|fl|r|b|d|vs|No|Co|Inc|Ltd|U\.S|U\.K|e\.g|i\.e|etc|approx)\.$/;

function sentences(text){
  const out = [];
  let start = 0;
  for (let i = 0; i < text.length; i++){
    const ch = text[i];
    if ((ch === '.' || ch === '!' || ch === '?') && /\s/.test(text[i + 1] || ' ')){
      const head = text.slice(start, i + 1);
      if (ch === '.' && ABBR.test(head)) continue;
      const next = text.slice(i + 1).trimStart()[0];
      if (next && !/[A-Z0-9"'“‘]/.test(next)) continue;
      out.push(head.trim()); start = i + 1;
    }
  }
  if (text.slice(start).trim()) out.push(text.slice(start).trim());
  return out;
}

// Plain-text intro → one or two clean sentences of at most MAX_LEN characters (+ "…"), or null if not useful.
export function trimSummary(raw){
  if (!raw) return null;
  let t = String(raw).split(/\n/)[0];
  let prev;
  do { prev = t; t = t.replace(/\s*\([^()]*\)/g, '').replace(/\s*\[[^\[\]]*\]/g, ''); } while (t !== prev);
  t = t.replace(/\s+/g, ' ').replace(/\s+([,.;:!?])/g, '$1').replace(/,\s*,/g, ',').trim();
  if (/may (also )?refer to/i.test(t)) return null;
  const s = sentences(t);
  if (!s.length) return null;
  let out = s[0];
  if (out.length < SHORT && s[1] && out.length + 1 + s[1].length <= MAX_LEN) out += ' ' + s[1];
  if (out.length > MAX_LEN){
    const cut = out.slice(0, MAX_LEN), sp = cut.lastIndexOf(' ');
    out = (sp > MAX_LEN * 0.6 ? cut.slice(0, sp) : cut).replace(/[\s,;:–—-]+$/, '') + '…';
  }
  if (/[()\[\]]/.test(out)) return null;   // an unbalanced bracket survived: the intro is too messy to show
  return out.length >= MIN_LEN ? out : null;
}

async function fetchBatch(api, titles){
  const normMap = {}, redirMap = {}, text = {}, out = {};
  let cont = null, guard = 0, requests = 0;
  do {
    const params = new URLSearchParams({ action: 'query', format: 'json', formatversion: '2', prop: 'extracts', exintro: '1', explaintext: '1', exlimit: String(BATCH), redirects: '1', titles: titles.join('|') });
    if (cont) Object.keys(cont).forEach(k => params.set(k, cont[k]));
    const j = await getJSON(api + '?' + params.toString()); requests++;
    const q = j.query || {};
    (q.normalized || []).forEach(x => { normMap[x.from] = x.to; });
    (q.redirects || []).forEach(x => { redirMap[x.from] = x.to; });
    (q.pages || []).forEach(pg => { if (pg.extract && text[pg.title] == null) text[pg.title] = pg.extract; });
    cont = j.continue || null; guard++;
    if (cont) await sleep(PAUSE_MS);
  } while (cont && guard < 10);
  titles.forEach(t => { let x = normMap[t] || t; x = redirMap[x] || x; if (text[x] != null) out[t] = text[x]; });
  return { text: out, requests };
}

function summariesLiteral(updated, perPrompt){
  const lines = Object.keys(perPrompt).sort().map(id =>
    `${id}:{` + Object.entries(perPrompt[id]).map(([d, s]) => `${JSON.stringify(d)}:${JSON.stringify(s)}`).join(',') + '},');
  return `/* Reveal summaries — GENERATED by tools/summaries.mjs on ${updated}. Do not edit by hand (Feature Spec 06).
   p.<prompt id>.<answer display> = first sentence(s) of the Wikipedia article (CC BY-SA 4.0), for tier ${MIN_TIER}–6 answers.
   Loaded async; the reveal screen simply shows nothing until it has arrived. */
const SUMMARIES = {updated:'${updated}', p:{
${lines.join('\n')}
}};
`;
}

async function main(){
  const argv = process.argv.slice(2);
  const dry = argv.includes('--dry-run');
  const apiArg = argv.indexOf('--api');                       // only for testing failures
  const api = apiArg !== -1 ? argv[apiArg + 1] : 'https://en.wikipedia.org/w/api.php';

  // Load with the current rarity (tiers decide what is rare) but without old summaries.
  const G = loadGame(HTML_FILE, fs.readFileSync(HTML_FILE, 'utf8'), { 'js/data/summaries.js': '' });
  const rare = [];
  for (const p of G.PROMPTS) for (const a of p.answers) if ((a.liveTier || a.tier) >= MIN_TIER) rare.push({ p, a });
  const titles = [...new Set(rare.map(x => x.a.wiki))];
  const batches = [];
  for (let i = 0; i < titles.length; i += BATCH) batches.push(titles.slice(i, i + BATCH));
  console.log(`${rare.length} answers with tier >= ${MIN_TIER}, ${titles.length} Wikipedia titles, ${batches.length} batches.`);

  const text = {};
  let failed = 0, requests = 0;
  for (let i = 0; i < batches.length; i++){
    try{
      const r = await fetchBatch(api, batches[i]);
      Object.assign(text, r.text); requests += r.requests;
    }catch(e){
      failed++;
      console.warn(`batch ${i + 1} failed: ${e.message}`);
      if (failed > batches.length * MAX_FAIL_SHARE){ console.error(`More than ${MAX_FAIL_SHARE * 100} % of the batches failed. Nothing was written.`); process.exit(1); }
    }
    if ((i + 1) % 25 === 0 || i + 1 === batches.length) console.log(`  ${i + 1}/${batches.length} batches`);
    await sleep(PAUSE_MS);
  }

  const perPrompt = {};
  let kept = 0, dropped = 0;
  for (const { p, a } of rare){
    const s = trimSummary(text[a.wiki]);
    if (!s){ dropped++; continue; }
    (perPrompt[p.id] = perPrompt[p.id] || {})[a.display] = s; kept++;
  }
  const updated = new Date().toISOString().slice(0, 10);
  const src = summariesLiteral(updated, perPrompt);
  console.log(`${requests} requests, ${failed} failed batches. ${kept} summaries kept, ${dropped} answers without a usable intro.`);
  console.log(`summaries.js would be ${(Buffer.byteLength(src) / 1024).toFixed(0)} KB.`);
  if (dry){ console.log('Dry run: nothing written.'); return; }
  fs.writeFileSync(OUT_FILE, src);
  console.log(`Wrote ${OUT_FILE}. Check the diff and run npm test.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
